// Builds dist/app.bundle.js: the ES modules in src/ joined into one classic script, used only when the app
// is opened directly from disk (file://), where browsers refuse to load modules. No dependencies.
// Usage: node tools/build.js          (CI checks that the committed bundle is up to date)
'use strict';
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const srcDir = path.join(root, 'src');

// Order: the import order of main.js (all top-level names are unique across modules, so they can share one scope)
const mainSrc = fs.readFileSync(path.join(srcDir, 'main.js'), 'utf8');
const order = [...mainSrc.matchAll(/^import\s+(?:[^'"]*from\s+)?['"]\.\/([\w-]+)\.js['"];/gm)].map(m => m[1]);

const strip = code => code
    .replace(/^import\s[^;]*;\s*$/gm, '')                 // import lines (single line each)
    .replace(/^export\s*\{[^}]*\};?\s*$/gm, '');          // export lists

const parts = order.map(name => `// ---- src/${name}.js ----\n${strip(fs.readFileSync(path.join(srcDir, `${name}.js`), 'utf8')).trim()}\n`);
parts.push(`// ---- src/main.js ----\n${strip(mainSrc).trim()}\n`);

const out = `/* Generated by tools/build.js from src/*.js. Do not edit: change the modules and rebuild. */\n(function () {\n'use strict';\n\n${parts.join('\n')}\n})();\n`;
fs.mkdirSync(path.join(root, 'dist'), { recursive: true });
fs.writeFileSync(path.join(root, 'dist', 'app.bundle.js'), out);
console.log(`dist/app.bundle.js written from ${order.length + 1} modules (${(out.length / 1024).toFixed(0)} KB)`);

// The resampling engine for the background worker (classic script loaded with importScripts): the same
// code as src/validation-core.js, so Option C runs identical code in the worker and on the page
const vcSrc = fs.readFileSync(path.join(srcDir, 'validation-core.js'), 'utf8');
fs.writeFileSync(path.join(root, 'dist', 'validation-core.worker.js'),
    `/* Generated by tools/build.js from src/validation-core.js for compute-worker.js. Do not edit. */\n${strip(vcSrc).trim()}\n`);
console.log('dist/validation-core.worker.js written');

// Cache-busting import map: each module URL gets a content hash, so browsers re-fetch a module only when it
// changes (written into index.html between the IMPORTMAP markers; the entry script is versioned the same way)
const crypto = require('crypto');
const hash = file => crypto.createHash('sha1').update(fs.readFileSync(file)).digest('hex').slice(0, 10);
const files = fs.readdirSync(srcDir).filter(f => f.endsWith('.js')).sort();
const map = { imports: {} };
files.forEach(f => { map.imports[`./src/${f}`] = `./src/${f}?h=${hash(path.join(srcDir, f))}`; });
['data-engine.js', 'models.js', 'compute-worker.js', 'dist/validation-core.worker.js'].forEach(f => { if (fs.existsSync(path.join(root, f))) map.imports[`./${f}`] = `./${f}?h=${hash(path.join(root, f))}`; });
const indexPath = path.join(root, 'index.html');
let html = fs.readFileSync(indexPath, 'utf8');
const block = `<!-- IMPORTMAP:START (generated by tools/build.js) -->\n    <script type="importmap">${JSON.stringify(map)}</script>\n    <!-- IMPORTMAP:END -->`;
if (/<!-- IMPORTMAP:START[\s\S]*?IMPORTMAP:END -->/.test(html)) html = html.replace(/<!-- IMPORTMAP:START[\s\S]*?IMPORTMAP:END -->/, block);
else html = html.replace(/(\s*)<script type="module" src="src\/main\.js[^"]*"><\/script>/, `$1${block}$&`);
html = html.replace(/<script type="module" src="src\/main\.js[^"]*"><\/script>/, `<script type="module" src="src/main.js?h=${hash(path.join(srcDir, 'main.js'))}"></script>`);
['data-engine.js', 'models.js'].forEach(f => { html = html.replace(new RegExp(`<script src="${f.replace('.', '\\.')}(\\?[^"]*)?"></script>`), `<script src="${f}?h=${hash(path.join(root, f))}"></script>`); });
// The stylesheet is versioned by content too, so a style change reaches users at once
html = html.replace(/<link rel="stylesheet" href="style\.css(\?[^"]*)?">/, `<link rel="stylesheet" href="style.css?h=${hash(path.join(root, 'style.css'))}">`);
// Content-Security-Policy: inline scripts are allowed only by their hashes (the import map and the file://
// loader), so injected inline script or event-handler attributes cannot run
const inline = [...html.matchAll(/<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/g)].map(m => m[1]);
const hashes = inline.map(code => `'sha256-${crypto.createHash('sha256').update(code, 'utf8').digest('base64')}'`);
html = html.replace(/script-src [^;]*;/, `script-src 'self' ${hashes.join(' ')} 'unsafe-eval';`);
fs.writeFileSync(indexPath, html);
console.log(`index.html import map, script versions and CSP hashes (${hashes.length} inline scripts) updated`);
